const TONE_BY_GROUP = {
  severity: { LOW: "info" },
  riskLevel: { LOW: "success" },
  matchStatus: { CONFIRMED: "success", REJECTED: "neutral" },
};

export function label(group, code) {
  if (code === null || code === undefined || code === "") return "";
  return LABELS[group]?.[String(code)] ?? String(code);
}

export function tone(group, code) {
  return TONE_BY_GROUP[group]?.[String(code)] ?? TONE_DEFAULT[String(code)] ?? "neutral";
}

/** Danh sách lựa chọn cho <select> từ một nhóm nhãn */
export function options(group, codes) {
  const map = LABELS[group] || {};
  return (codes || Object.keys(map)).map((c) => ({ value: c, label: map[c] ?? c }));
}
